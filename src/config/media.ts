/** Turns a YouTube or Vimeo link into a privacy-friendly player address. Null when it is neither. */
export function embedUrl(url: string): string | null {
  let u: URL;
  try {
    u = new URL(url);
  } catch {
    return null;
  }
  const host = u.hostname.replace(/^www\.|^m\./, "");
  const clean = (id: string | null | undefined) => (id && /^[\w-]{5,20}$/.test(id) ? id : null);
  if (host === "youtu.be" || host === "youtube.com" || host === "youtube-nocookie.com") {
    const id = clean(
      host === "youtu.be"
        ? u.pathname.slice(1)
        : (u.searchParams.get("v") ?? u.pathname.split("/").filter(Boolean)[1]),
    );
    return id ? `https://www.youtube-nocookie.com/embed/${id}?autoplay=1&rel=0` : null;
  }
  if (host === "vimeo.com" || host === "player.vimeo.com") {
    const id = clean(u.pathname.split("/").filter(Boolean).at(-1));
    return id ? `https://player.vimeo.com/video/${id}?autoplay=1&dnt=1` : null;
  }
  return null;
}
